-- Esquema inicial de Taquímetro: tablas, permisos (GRANT y RLS), función bayesiana,
-- trigger de agregados, bucket de fotos y Realtime. La semilla va en otra migración.
-- Referencia: docs/arquitectura.md, secciones 2, 3 y 4.

-- ---------------------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------------------

create table public.taquerias (
  id bigint generated by default as identity primary key,
  nombre text not null,
  alcaldia text,
  latitud double precision,
  longitud double precision
);

create table public.calificaciones (
  id bigint generated always as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  taqueria_id bigint not null references public.taquerias (id),
  salsa smallint not null check (salsa between 1 and 5),
  tortilla smallint not null check (tortilla between 1 and 5),
  carne smallint not null check (carne between 1 and 5),
  puntaje numeric generated always as ((salsa + tortilla + carne) / 3.0) stored,
  precio numeric(6, 2) not null check (precio between 5 and 150),
  copia boolean not null,
  creada_en timestamptz not null default now(),
  unique (user_id, taqueria_id)
);

create table public.fotos (
  id bigint generated always as identity primary key,
  taqueria_id bigint not null references public.taquerias (id),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  ruta text not null unique,
  creada_en timestamptz not null default now()
);

create table public.agregados_taqueria (
  taqueria_id bigint primary key references public.taquerias (id),
  votos integer not null default 0,
  prom_salsa numeric,
  prom_tortilla numeric,
  prom_carne numeric,
  precio_promedio numeric,
  porcentaje_copia numeric,
  puntaje_bayesiano numeric
);

-- ---------------------------------------------------------------------------
-- RLS en todas las tablas
-- ---------------------------------------------------------------------------

alter table public.taquerias enable row level security;
alter table public.calificaciones enable row level security;
alter table public.fotos enable row level security;
alter table public.agregados_taqueria enable row level security;

-- ---------------------------------------------------------------------------
-- GRANT explícitos. Primero se quita todo para no depender de privilegios por defecto.
-- ---------------------------------------------------------------------------

revoke all on table public.taquerias from anon, authenticated;
revoke all on table public.calificaciones from anon, authenticated;
revoke all on table public.fotos from anon, authenticated;
revoke all on table public.agregados_taqueria from anon, authenticated;

-- taquerias: solo lectura.
grant select on table public.taquerias to anon, authenticated;

-- calificaciones: solo con sesión. user_id y creada_en se llenan solos.
grant select on table public.calificaciones to authenticated;
grant insert (taqueria_id, salsa, tortilla, carne, precio, copia)
  on table public.calificaciones to authenticated;
grant update (salsa, tortilla, carne, precio, copia)
  on table public.calificaciones to authenticated;

-- fotos: lectura pública; con sesión se inserta y se borra.
grant select on table public.fotos to anon, authenticated;
grant insert (taqueria_id, ruta) on table public.fotos to authenticated;
grant delete on table public.fotos to authenticated;

-- agregados_taqueria: solo lectura; escribe el trigger.
grant select on table public.agregados_taqueria to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Políticas RLS. (select auth.uid()) evalúa el id una vez por consulta y no por fila.
-- ---------------------------------------------------------------------------

create policy "Todos leen las taquerías"
  on public.taquerias for select
  to anon, authenticated
  using (true);

create policy "Cada usuario lee sus calificaciones"
  on public.calificaciones for select
  to authenticated
  using (user_id = (select auth.uid()));

create policy "Cada usuario inserta sus calificaciones"
  on public.calificaciones for insert
  to authenticated
  with check (user_id = (select auth.uid()));

create policy "Cada usuario edita sus calificaciones"
  on public.calificaciones for update
  to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

create policy "Todos leen las fotos"
  on public.fotos for select
  to anon, authenticated
  using (true);

create policy "Cada usuario registra fotos en su carpeta"
  on public.fotos for insert
  to authenticated
  with check (
    user_id = (select auth.uid())
    and split_part(ruta, '/', 1) = (select auth.uid())::text
  );

create policy "Cada usuario borra sus fotos"
  on public.fotos for delete
  to authenticated
  using (user_id = (select auth.uid()));

create policy "Todos leen los agregados"
  on public.agregados_taqueria for select
  to anon, authenticated
  using (true);

-- ---------------------------------------------------------------------------
-- Función bayesiana: pura, no lee tablas.
-- v = votos, r = promedio de la taquería, m = promedio global, c = peso.
-- ---------------------------------------------------------------------------

create function public.puntaje_bayesiano(v integer, r numeric, m numeric, c numeric)
returns numeric
language sql
immutable
security invoker
set search_path = ''
as $$
  select case
    when v is null or v = 0 or r is null or m is null then null
    else (v / (v + c)) * r + (c / (v + c)) * m
  end;
$$;

revoke execute on function public.puntaje_bayesiano(integer, numeric, numeric, numeric)
  from public, anon, authenticated;
grant execute on function public.puntaje_bayesiano(integer, numeric, numeric, numeric)
  to anon, authenticated;

-- ---------------------------------------------------------------------------
-- Trigger de agregados: recalcula las 20 filas con cada inserción, edición o borrado.
-- La app no borra calificaciones; el borrado llega en cascada al borrar un usuario de prueba.
-- security definer para ver todas las calificaciones; search_path vacío y nombres completos.
-- ---------------------------------------------------------------------------

create function public.recalcular_agregados()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  promedio_global numeric;
begin
  select avg(puntaje) into promedio_global from public.calificaciones;

  update public.agregados_taqueria a
  set
    votos = s.votos,
    prom_salsa = s.prom_salsa,
    prom_tortilla = s.prom_tortilla,
    prom_carne = s.prom_carne,
    precio_promedio = s.precio_promedio,
    porcentaje_copia = s.porcentaje_copia,
    puntaje_bayesiano = public.puntaje_bayesiano(s.votos, s.prom_puntaje, promedio_global, 3)
  from (
    select
      t.id as taqueria_id,
      count(c.id)::integer as votos,
      avg(c.salsa) as prom_salsa,
      avg(c.tortilla) as prom_tortilla,
      avg(c.carne) as prom_carne,
      avg(c.precio) as precio_promedio,
      avg(c.copia::integer) * 100 as porcentaje_copia,
      avg(c.puntaje) as prom_puntaje
    from public.taquerias t
    left join public.calificaciones c on c.taqueria_id = t.id
    group by t.id
  ) s
  where a.taqueria_id = s.taqueria_id;

  return null;
end;
$$;

revoke execute on function public.recalcular_agregados() from public, anon, authenticated;

create trigger recalcular_agregados
  after insert or update or delete on public.calificaciones
  for each statement
  execute function public.recalcular_agregados();

-- ---------------------------------------------------------------------------
-- Bucket fotos: público, 5 MB, solo JPG y PNG. Cada usuario en su carpeta <user_id>/.
-- Sin política de update: no se reemplazan archivos.
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('fotos', 'fotos', true, 5242880, array['image/jpeg', 'image/png']);

create policy "Cada usuario lista su carpeta de fotos"
  on storage.objects for select
  to authenticated
  using (
    bucket_id = 'fotos'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

create policy "Cada usuario sube a su carpeta de fotos"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'fotos'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

create policy "Cada usuario borra en su carpeta de fotos"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'fotos'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

-- ---------------------------------------------------------------------------
-- Realtime: solo agregados_taqueria (D8).
